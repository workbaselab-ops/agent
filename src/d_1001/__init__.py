# from 같은 경로의 app.py 파일에서 main 함수를 가져온다.
# from 뒤에 있는 .app은 현재 디렉토리의 app.py를 의미한다.
# 다음으로 main 함수를 가져와서 현재 모듈의 __all__ 리스트에 추가한다. __all__ 리스트는 이 모듈에서 공개적으로 사용할 수 있는 이름들을 정의한다.
# 다른 모듈에서 from agent import *를 사용할 때, __all__에 정의된 이름들만 가져오게 된다. 따라서 main 함수만 공개적으로 사용할 수 있게 된다.
# 다른 폴더에서 agent 모듈을 import할 때, main 함수만 사용할 수 있게 된다. 이는 모듈의 인터페이스를 명확하게 정의하고, 불필요한 내부 구현 세부 사항을 숨기는 데 도움이 된다.
# 다른 폴더에 있는 파일을 가져오려면 from .app import main과 같이 상대 경로를 사용해야 한다. 이는 현재 디렉토리에서 app.py를 찾도록 지시한다. 만약 절대 경로를 사용하면, 다른 위치에 있는 모듈을 가져오게 되어 의도치 않은 동작을 초래할 수 있다.
# 다른 폴더에 있는 파이썬 파일을 가져오려면, 해당 폴더가 파이썬 경로에 포함되어 있어야 한다. 그렇지 않으면 ImportError가 발생할 수 있다. 따라서 프로젝트 구조를 잘 설계하고, 필요한 경우 sys.path를 수정하거나 PYTHONPATH 환경 변수를 설정하여 모듈을 올바르게 가져올 수 있도록 해야 한다.
# 다른 경로에 있는 파일의 경로를 표시하는 방법은 다음과 같다. 예를 들어, 현재 디렉토리에서 상위 디렉토리로 이동하려면 from ..module import function과 같이 두 개의 점(..)을 사용하여 상위 디렉토리를 나타낼 수 있다. 이는 상대 경로를 사용하여 모듈을 가져오는 방법 중 하나이다.

# import 뒤에 나오는 것음 함수나 클래스, 변수 등을 가져오는 것을 의미한다. 예를 들어, from .app import main은 현재 디렉토리의 app.py 파일에서 main 함수를 가져오는 것을 의미한다. 이렇게 하면 다른 모듈에서 agent 모듈을 import할 때, main 함수만 사용할 수 있게 된다.

from .app import main

__all__=["main"]


